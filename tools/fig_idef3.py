def _cross(c, x, y, w=26, h=13, num="", name="", size=7.6):
    c.rect(x, y, w, h)
    if num:
        c.text(x + 1.8, y + h - 2.6, num, size=6.4, ha="left")
    c.text(x + w / 2, y + h / 2 + (2.2 if num else 0), name, size=size,
           wrap=int(w * 0.42))
    return {"l": (x, y + h / 2), "r": (x + w, y + h / 2),
            "t": (x + w / 2, y), "b": (x + w / 2, y + h),
            "cx": x + w / 2, "cy": y + h / 2}


def idef3_example():
    c = Canvas(196, 100)
    c.text(c.w / 2, 4, "IDEF3-диаграмма «Сборка настольных компьютеров»",
           size=9, bold=True)

    u1 = _cross(c, 6, 40, 28, 14, "1", "Подготовка компонентов")
    j1 = idef3_junction(c, 46, 47, "O", 1)
    u2 = _cross(c, 60, 16, 28, 15, "2", "Установка материнской платы "
                                        "и винчестера", 6.4)
    u3 = _cross(c, 60, 40, 28, 13, "3", "Установка модема")
    u4 = _cross(c, 60, 62, 28, 13, "4", "Установка CD-ROM")
    j2 = idef3_junction(c, 106, 47, "X", 2)
    u5 = _cross(c, 118, 16, 30, 13, "5", "Установка флоппи-дисковода", 6.8)
    u6 = _cross(c, 118, 40, 30, 13, "6", "Инсталляция ОС")
    u7 = _cross(c, 118, 62, 30, 13, "7", "Инсталляция доп. ПО", 6.8)
    ref = idef3_referent(c, 160, 38, 32, 18, "Программное обеспечение")

    # 1 → J1
    c.arrow([u1["r"], (j1["l"][0], j1["l"][1])], head="open")
    # J1 → работы 2, 3, 4
    c.arrow([(j1["r"][0], j1["r"][1]), (52, j1["r"][1]), (52, u2["l"][1]),
             u2["l"]], head="filled")
    c.arrow([(j1["r"][0], j1["r"][1]), u3["l"]], head="filled")
    c.arrow([(j1["r"][0], j1["r"][1]), (52, j1["r"][1]), (52, u4["l"][1]),
             u4["l"]], head="filled")
    # работы 2, 3, 4 → J2 (слияние исключающего «ИЛИ»)
    c.arrow([u2["r"], (92, u2["r"][1]), (92, j2["l"][1]),
             (j2["l"][0], j2["l"][1])], head="open")
    c.arrow([u3["r"], (j2["l"][0], j2["l"][1])], head="open")
    c.arrow([u4["r"], (92, u4["r"][1]), (92, j2["l"][1]),
             (j2["l"][0], j2["l"][1])], head="open")
    # J2 → работы 5, 6, 7
    c.arrow([(j2["r"][0], j2["r"][1]), (112, j2["r"][1]), (112, u5["l"][1]),
             u5["l"]], head="filled")
    c.arrow([(j2["r"][0], j2["r"][1]), u6["l"]], head="filled")
    c.arrow([(j2["r"][0], j2["r"][1]), (112, j2["r"][1]), (112, u7["l"][1]),
             u7["l"]], head="filled")
    # объект ссылки «Программное обеспечение»
    c.arrow([u5["r"], (154, u5["r"][1]), (154, ref["t"][1] - 2), (ref["t"][0],
             ref["t"][1])], head="open", ls=(0, (4, 2)))
    c.arrow([u6["r"], ref["l"]], head="open", ls=(0, (4, 2)))
    c.arrow([u7["r"], (154, u7["r"][1]), (154, ref["b"][1] + 2),
             (ref["b"][0], ref["b"][1])], head="open", ls=(0, (4, 2)))
    # «Компоненты» — объект ссылки на первой работе
    c.arrow([(2, 28), (16, 28), (16, u1["t"][1])], head="open", ls=(0, (4, 2)))
    c.text(16, 22, "Компоненты", size=6.8)
    c.text(c.w / 2, c.h - 4,
           "1 — асинхронное «ИЛИ» (J1), 2 — исключающее «ИЛИ» (J2); "
           "пунктир — объект ссылки", size=7, italic=True)
    return c.save("idef3_example")


