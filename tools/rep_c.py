from docx_report import Report

VARIANT = "3 — Агентство недвижимости"


def _uml_report(number, theme, goal, tasks, extra_note, example_imgs,
                variant_imgs, tables, qa, conclusion, name):
    r = Report(number, theme, "", VARIANT, "ПК, MS Visio / Ramus, MS Word")
    r.h1(f"ПРАКТИЧЕСКАЯ РАБОТА № {number}")
    r.p(f"Тема: «{theme}».", align="center", bold=True, first_line=False)
    r.goal_block(goal, tasks, "Персональный компьютер, MS Office Visio "
                "(набор элементов UML), Microsoft Word.")
    r.h2("1 Краткие теоретические сведения")
    for para in extra_note["theory"]:
        r.p(para)
    r.h2("2 Пример по методическим указаниям")
    for para in extra_note["example_text"]:
        r.p(para)
    for img, cap, w in example_imgs:
        r.image(img, cap, width_cm=w)
    r.h2(f"3 Диаграмма по варианту 3 — «Агентство недвижимости»")
    for para in extra_note["variant_text"]:
        r.p(para)
    for img, cap, w in variant_imgs:
        r.image(img, cap, width_cm=w)
    n = 4
    for header, rows, caption, widths in tables:
        r.h2(f"{n} {caption}")
        n += 1
        r.table(header, rows, caption, widths=widths)
    r.questions(qa)
    r.conclusion(conclusion)
    return r.save(name)


